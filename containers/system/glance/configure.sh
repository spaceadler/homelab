#!/usr/bin/env bash
# Write config/apps.yml: a monitor widget listing every installed app, from
# containers/catalog.tsv. Runs on every ./install.sh, so it always matches
# what's installed.
set -euo pipefail

out=config/apps.yml
{
    echo "# Generated by install.sh from containers/catalog.tsv. Edits are overwritten;"
    echo "# put your own widgets in home.yml instead."
    echo "- type: monitor"
    echo "  title: Homelab"
    echo "  cache: 1m"
    echo "  sites:"
    while IFS=$'\t' read -r _genre app sub port icon name _about; do
        if [[ " $HOMELAB_APPS " != *" $app "* ]] || [ "$sub" = "-" ]; then continue; fi
        echo "    - title: $name"
        if [ "$app" = vaultwarden ]; then
            # Bound to 127.0.0.1 and served only by tailscale serve.
            echo "      url: https://$VAULT_HOST"
        else
            echo "      url: $URL_SCHEME://$sub.$DOMAIN"
            echo "      check-url: http://host.docker.internal:$port"
        fi
        if [ "$icon" != "-" ]; then echo "      icon: $icon"; fi
    done < <(grep -vE '^[[:space:]]*(#|$)' "$HOMELAB_CATALOG")
} > "$out"
